def _eps_weekly_hulu(premiere: str, batch: int, total: int) -> list[dict]:
    """Hulu weekly cadence with a multi-episode premiere batch.

    Eps 1..batch share the premiere date; each later ep lands 7 days
    after the one before it. Only episodes released by the pull date
    belong in `total` - the caller excludes unaired episodes.
    """
    from datetime import timedelta
    start_dt = datetime.strptime(premiere, "%Y-%m-%d")
    eps: list[dict] = []
    for i in range(total):
        weeks_after = 0 if i < batch else (i - batch + 1)
        eps.append({
            "episode_num":   i + 1,
            "air_date":      start_dt + timedelta(days=7 * weeks_after),
            "display_label": f"Episode {i + 1}",
        })
    return eps


