"""Subjects people ask about that we do not hold (Jenna, 2026-11-23).

Jenna approved building profiles for subjects people ask about that we do
not hold. Last week Emma Crouchen asked about VICE Sports, the library had
no VICE Sports profile, and the answer borrowed the Pinterest profile open
on her screen.

What happens now
----------------
1. Every read on a subject we do not hold records the subject (one key for
   every spelling: case, punctuation, a leading "the" and a trailing
   "fans" / "audience" set aside; the spellings people used are kept as
   aliases) and the audience size the read's research found. The size is
   saved the way the VICE Sports size was: in the saved-size table (a
   runtime table beside scripts/_subject_estimates, read by
   migration/saved_subject_size) and as a record anchor in the Prometheus
   anchor store, so later builds and answers land on the same figure. The
   first size saved for a subject stands.
2. The reader's answer ends with a plain offer to build a full profile at
   their own build price, once per thread (prometheus/build_offer.py in the
   web app). The offer is a line and a chip; the chip asks for the build,
   which goes through the standard brief and the reader's own approval.
   Nothing is charged or queued for anyone.
3. Once a week (Mondays, unheld-subjects-weekly.timer) Jenna, and only
   Jenna, gets the subjects asked about most that we still do not hold,
   with how many people asked and the audience size, so she can approve
   house builds. Her approval is the standard path: she asks Prometheus for
   the build and approves the brief, and the build starts from the saved
   size. An empty week sends nothing; a week sends once.

Catalog rules: a subject the catalog carries (the profiles in the Select
Profile list, matched on the normalized entity name, so a cut counts as its
parent) is never recorded and never offered. The subject is always the one
the words named, never the profile open on the screen.

Stores (dashboard-inputs bucket, ETag compare-and-swap):
    system/unheld_subjects/index.json   asks, sizes and offers per subject
    system/unheld_subjects/weekly.json  the weeks already sent
    system/saved_subject_sizes.json     the saved-size table
    system/pm_anchors/<key>.json        the record anchor

Lives in both repos (migration/ in the parent, bg-webapp/migration/ in the
web app, generated by scripts/sync_module_twins.py); keep the twins
byte-equal. Never raises into a request. Regression:
scripts/test_unheld_subjects.py.
"""
from __future__ import annotations

import datetime as _dt
import json
import os
import re
import threading
import time

BUCKET = 'dashboard-inputs'
INDEX_KEY = 'system/unheld_subjects/index.json'
WEEKLY_KEY = 'system/unheld_subjects/weekly.json'
TABLE_KEY = 'system/saved_subject_sizes.json'
CATALOG_KEY = 'system/s3_cache.json'
QUICK_SELECTS_KEY = 'metadata/admin_quick_selects.json'
WEEKLY_TO = ('jenna@crosswalknyc.com',)
WEEKLY_FROM = 'BehavioralGraph <jenna@crosswalknyc.com>'
SES_REGION = 'us-east-2'
WEEK_DAYS = 7
WEEKLY_MAX_ROWS = 15
MAX_ASKS = 400          # asks kept per subject, newest last
MAX_OFFERS = 400        # thread offers kept per subject
MAX_ALIASES = 24
CATALOG_TTL_S = 300
PROBE_PREFIXES = ('canary:', 'probe:')

# Hermetic hooks for tests: an S3-like store, an SES-like client and the
# display names of the profiles the catalog holds.
STORE_FOR_TESTS = None
SES_FOR_TESTS = None
CATALOG_FOR_TESTS = None

_cat = {'ts': 0.0, 'held': None}
_cat_lock = threading.Lock()


def _hermetic():
    return str(os.environ.get('REGRESSION_TEST_MODE', '')).strip() == '1'


def _log(msg):
    try:
        print(f"[unheld-subjects] {msg}", flush=True)
    except Exception:
        pass


def _s3():
    if STORE_FOR_TESTS is not None:
        return STORE_FOR_TESTS
    if _hermetic():
        return None
    try:
        import boto3
        return boto3.client('s3')
    except Exception:
        return None


def _ss():
    from migration import saved_subject_size as m
    return m


def _now(now=None):
    return now or _dt.datetime.now(_dt.timezone.utc)


def _iso(d):
    return d.strftime('%Y-%m-%dT%H:%M:%SZ')


def _parse(ts):
    try:
        d = _dt.datetime.fromisoformat(str(ts or '').strip().replace('Z', '+00:00'))
        return d if d.tzinfo else d.replace(tzinfo=_dt.timezone.utc)
    except Exception:
        return None


def _load_json(s3, key):
    try:
        obj = s3.get_object(Bucket=BUCKET, Key=key)
        return json.loads(obj['Body'].read().decode('utf-8'))
    except Exception:
        return None


def _update(s3, key, mutate):
    from migration.s3_json_state import update_json
    return update_json(BUCKET, key, mutate, default={}, s3=s3)


# ------------------------------------------------------------------ names
_GENERIC_TAIL_RX = re.compile(r"(?:\s+(?:fans?|audiences?|fanbase|fan base))+\s*$", re.I)


def subject_name(subject) -> str:
    """The subject as a reader writes it, without a cut suffix and without a
    trailing 'fans' / 'audience' ('VICE Sports - Men 35+' and 'VICE Sports
    fans' are VICE Sports). Case and inner punctuation are kept."""
    s = ' '.join(str(subject or '').replace('\u2019', "'").split())
    s = s.split(' - ', 1)[0].strip(" \"'.,;:")
    t = _GENERIC_TAIL_RX.sub('', s).strip()
    return t or s


def spelling(subject) -> str:
    """A spelling as a reader wrote it (spaces tidied, a cut suffix and
    outer quotes dropped), kept as an alias."""
    s = ' '.join(str(subject or '').replace('\u2019', "'").split())
    return s.split(' - ', 1)[0].strip(" \"'.,;:")


def subject_key(subject) -> str:
    """One key for every spelling of a subject (saved_subject_size.core)."""
    try:
        return _ss().core(subject_name(subject))
    except Exception:
        return ''


def is_probe_user(user) -> bool:
    u = str(user or '').strip().lower()
    return u.startswith(PROBE_PREFIXES)


def window_pair(window):
    """(start, end) ISO strings from a {'start','end'} dict, a pair or a
    'YYYY-MM-DD TO YYYY-MM-DD' string; None when there is none."""
    try:
        w = _ss().parse_window(window)
        return (w[0].isoformat(), w[1].isoformat()) if w else None
    except Exception:
        return None


# ---------------------------------------------------------------- catalog
def _held_keys(s3=None):
    """The keys of every profile in the Select Profile list (admin-hidden
    profiles left out, as the build step's match leaves them out). None
    when the catalog cannot be read. Cached a few minutes."""
    if CATALOG_FOR_TESTS is not None:
        return {k for k in (subject_key(n) for n in CATALOG_FOR_TESTS) if k}
    now = time.time()
    with _cat_lock:
        if _cat['held'] is not None and now - _cat['ts'] < CATALOG_TTL_S:
            return _cat['held']
    s3 = s3 or _s3()
    if s3 is None:
        return None
    cache = _load_json(s3, CATALOG_KEY)
    if not isinstance(cache, dict):
        return None
    qs = _load_json(s3, QUICK_SELECTS_KEY)
    profiles = (qs.get('profiles') or {}) if isinstance(qs, dict) else {}
    hidden = {k for k, v in profiles.items() if v is False} if isinstance(profiles, dict) else set()
    held = set()
    for j in cache.get('jobs') or []:
        if not isinstance(j, dict):
            continue
        key = str(j.get('s3_key') or j.get('key') or '')
        if not key or key in hidden or '/' in key or not key.lower().endswith('.csv'):
            continue
        for n in (j.get('display_name'), j.get('name'), j.get('project_name'), j.get('profile_subject')):
            k = subject_key(str(n or '').replace('_', ' '))
            if k:
                held.add(k)
    with _cat_lock:
        _cat.update(ts=now, held=held)
    return held


def catalog_holds(subject, s3=None):
    """True when the catalog carries a profile of the subject or of its
    parent (a cut derives from its parent), False when it does not, None
    when the catalog could not be read (callers stay conservative)."""
    k = subject_key(subject)
    if not k:
        return None
    held = _held_keys(s3)
    if held is None:
        return None
    return k in held


def clear_catalog_cache():
    with _cat_lock:
        _cat.update(ts=0.0, held=None)


# ------------------------------------------------------------------ sizes
def save_size(subject, people, *, window=None, question='', aliases=(), read_key='', s3=None, now=None):
    """Save the audience size a read found for a subject we do not hold:
    the saved-size table and a record anchor in the anchor store, the way
    the VICE Sports size was saved. A subject that already has a saved size
    keeps it. Returns {'sample', 'people', 'window', 'saved', 'source'} or
    None. Never raises."""
    try:
        ss = _ss()
        name = subject_name(subject)
        key = subject_key(name)
        p = int(round(float(people or 0)))
        if not key or p <= 0:
            return None
        have = ss.lookup(name)
        if have:
            return {'sample': int(have['tu']), 'people': int(have['us']), 'window': have.get('window'),
                    'saved': False, 'source': have.get('source')}
        sample = ss.sample_near(p)
        if not sample:
            return None
        us = ss.projected(sample)
        w = window_pair(window)
        s3 = s3 or _s3()
        if s3 is None:
            return None
        t = _iso(_now(now))
        names = [x for x in dict.fromkeys([spelling(a) for a in (aliases or ())]) if x and x != name]
        entry = {'name': name, 'aliases': names[:MAX_ALIASES], 'sample': sample, 'people': us,
                 'window': list(w) if w else None, 'saved_at': t, 'from': 'read', 'question': str(question or '')[:200]}
        wrote = {'table': False}

        def mutate(doc):
            doc = doc if isinstance(doc, dict) else {}
            subs = doc.setdefault('subjects', {})
            if key in subs:
                return None          # the first size saved stands
            subs[key] = entry
            doc['updated'] = t
            wrote['table'] = True
            return doc

        _update(s3, TABLE_KEY, mutate)
        if wrote['table']:
            write_record_anchor(name, us, w, s3=s3, now=now, read_key=read_key)
            _log(f"saved {name!r}: {sample:,} in the data, {us:,} US people"
                 + (f" ({w[0]} to {w[1]})" if w else ''))
        ss.clear_cache()
        got = ss.lookup(name)
        if got:
            return {'sample': int(got['tu']), 'people': int(got['us']), 'window': got.get('window'),
                    'saved': bool(wrote['table']), 'source': got.get('source')}
        return {'sample': sample, 'people': us, 'window': w, 'saved': bool(wrote['table']), 'source': 'saved_table'}
    except Exception as e:
        _log(f"size not saved for {subject!r}: {type(e).__name__}: {e}")
        return None


def saved_size(subject):
    """{'sample', 'people', 'window', 'source'} for the subject's saved size
    (any source migration/saved_subject_size reads), or None."""
    try:
        got = _ss().lookup(subject_name(subject))
        if got:
            return {'sample': int(got['tu']), 'people': int(got['us']), 'window': got.get('window'),
                    'source': got.get('source')}
    except Exception:
        pass
    return None


def anchor_record(name, people, window=None, now=None):
    """The record anchor for a saved size, in the anchor store's own shape."""
    w = window or None
    label = f"{name} audience in the US"
    label += f", {w[0]} to {w[1]}" if w else ", trailing 12 months"
    return {'name': label[:120], 'value': int(people), 'unit': 'people',
            'window': {'start': w[0], 'end': w[1]} if w else {'start': '', 'end': ''},
            'klass': 'audience', 'source_type': 'record', 'as_of': _now(now).strftime('%Y-%m-%d')}


def write_record_anchor(name, people, window=None, *, s3=None, now=None, read_key=''):
    """Put the record anchor where saved sizes are read back (the subject's
    any-window read and insight documents) and on the read's own research
    document when its key is known. Every other anchor, event and source on
    a document stays; a document's freshness stamp is never moved, and the
    read's own document is never created here."""
    s3 = s3 or _s3()
    if s3 is None:
        return 0
    import hashlib
    ss = _ss()
    rec = anchor_record(name, people, window, now)

    def doc_key(ask_key):
        return f"{ss.ANCHOR_PREFIX}{hashlib.sha1(str(ask_key).encode()).hexdigest()[:20]}.json"

    targets = [(doc_key(ak), ak, (ak.split('|') + ['', 'read'])[1] or 'read', True) for ak in ss.anchor_ask_keys(name)]
    if read_key:
        targets.append((doc_key(read_key), str(read_key), 'read', False))
    n, seen = 0, set()
    for dk, ak, product, create in targets:
        if dk in seen:
            continue
        seen.add(dk)

        def mutate(doc, _ak=ak, _product=product, _create=create):
            doc = doc if isinstance(doc, dict) else {}
            if not doc:
                if not _create:
                    return None
                doc = {'key': _ak, 'ask': {'subject': name, 'product': _product, 'family': 'audience',
                                           'window': {'start': '', 'end': ''}, 'scope': '', 'platform': ''},
                       'changed_windows': [], 'anchors': [], 'events': [], 'sources': [],
                       'saved_ts': time.time(), 'saved_at': _iso(_now(now))}
            keep = [a for a in (doc.get('anchors') or []) if not (isinstance(a, dict)
                    and str(a.get('source_type') or '') == 'record' and str(a.get('name') or '') == rec['name'])]
            doc['anchors'] = [rec] + keep[:39]
            return doc

        try:
            if _update(s3, dk, mutate) is not None:
                n += 1
        except Exception as e:
            _log(f"record anchor not written to {dk}: {type(e).__name__}: {e}")
    return n


# ------------------------------------------------------------------- asks
def record_read(subject, *, user, thread_id='', asked_as='', question='', size=None, probe=False, s3=None, now=None):
    """Note one read on a subject we do not hold: who asked, on which
    thread, the spelling they used, and the saved size when there is one.
    Probes never count. Returns the subject's entry or None. Never
    raises."""
    try:
        name = subject_name(subject)
        key = subject_key(name)
        if not key or probe or is_probe_user(user) or not str(user or '').strip():
            return None
        s3 = s3 or _s3()
        if s3 is None:
            return None
        t = _iso(_now(now))
        spellings = [x for x in dict.fromkeys([spelling(asked_as), name]) if x]

        def mutate(doc):
            doc = doc if isinstance(doc, dict) else {}
            subs = doc.setdefault('subjects', {})
            e = subs.setdefault(key, {'name': name, 'aliases': [], 'asks': [], 'offers': [], 'first_at': t})
            for f in ('aliases', 'asks', 'offers'):
                if not isinstance(e.get(f), list):
                    e[f] = []
            for s in spellings:
                if s != e.get('name') and s not in e['aliases']:
                    e['aliases'].append(s)
            e['aliases'] = e['aliases'][-MAX_ALIASES:]
            e['asks'].append({'user': str(user)[:120], 'ts': t, 'thread': str(thread_id or '')[:60],
                              'q': str(question or '')[:200]})
            e['asks'] = e['asks'][-MAX_ASKS:]
            e['last_at'] = t
            if isinstance(size, dict) and size.get('people') and not e.get('size'):
                e['size'] = {'sample': size.get('sample'), 'people': size.get('people'),
                             'window': list(size['window']) if size.get('window') else None}
            e.pop('held_at', None)
            doc['updated'] = t
            return doc

        out = _update(s3, INDEX_KEY, mutate)
        return dict(((out or {}).get('subjects') or {}).get(key) or {}) or None
    except Exception as e:
        _log(f"ask not recorded for {subject!r}: {type(e).__name__}: {e}")
        return None


def _offer_tag(user, thread_id):
    return f"{str(user or '').strip().lower()}|{str(thread_id or '').strip()}"


def offered(subject, user, thread_id, *, s3=None) -> bool:
    """True when this subject was already offered to this reader on this
    thread."""
    try:
        if not str(thread_id or '').strip():
            return False
        s3 = s3 or _s3()
        doc = _load_json(s3, INDEX_KEY) if s3 is not None else None
        e = ((doc or {}).get('subjects') or {}).get(subject_key(subject)) or {}
        return _offer_tag(user, thread_id) in (e.get('offers') or [])
    except Exception:
        return False


def mark_offered(subject, user, thread_id, *, s3=None, now=None) -> bool:
    try:
        key = subject_key(subject)
        if not key or not str(thread_id or '').strip():
            return False
        s3 = s3 or _s3()
        if s3 is None:
            return False
        tag = _offer_tag(user, thread_id)

        def mutate(doc):
            doc = doc if isinstance(doc, dict) else {}
            e = doc.setdefault('subjects', {}).setdefault(key, {'name': subject_name(subject), 'aliases': [], 'asks': [],
                                                               'offers': [], 'first_at': _iso(_now(now))})
            offers = e['offers'] if isinstance(e.get('offers'), list) else []
            if tag in offers:
                return None
            e['offers'] = (offers + [tag])[-MAX_OFFERS:]
            return doc

        _update(s3, INDEX_KEY, mutate)
        return True
    except Exception as e:
        _log(f"offer not marked for {subject!r}: {type(e).__name__}: {e}")
        return False


# ----------------------------------------------------------------- weekly
def week_bounds(now=None, days=WEEK_DAYS):
    end = _now(now)
    return end - _dt.timedelta(days=days), end


def week_tag(now=None):
    y, w, _ = _now(now).isocalendar()
    return f"{y}-W{w:02d}"


def weekly_rows(doc, *, now=None, days=WEEK_DAYS, s3=None, limit=WEEKLY_MAX_ROWS):
    """The subjects asked about in the week that the catalog still does not
    carry, most-asked first: [{'name', 'people_week', 'asks_week',
    'people_total', 'first_at', 'sample', 'people_size', 'key'}]."""
    lo, hi = week_bounds(now, days)
    held = _held_keys(s3)
    rows = []
    for key, e in ((doc or {}).get('subjects') or {}).items():
        if not isinstance(e, dict):
            continue
        asks = [a for a in (e.get('asks') or []) if isinstance(a, dict) and not is_probe_user(a.get('user'))]
        week = [a for a in asks if (lambda d: d is not None and lo <= d <= hi)(_parse(a.get('ts')))]
        if not week:
            continue
        name = str(e.get('name') or key)
        if held is not None and (key in held or subject_key(name) in held):
            continue              # built or carried since it was asked about
        size = e.get('size') if isinstance(e.get('size'), dict) else None
        if not (size and size.get('people')):
            got = None
            try:
                got = _ss().lookup(name)
            except Exception:
                got = None
            size = {'sample': got['tu'], 'people': got['us']} if got else None
        rows.append({'key': key, 'name': name,
                     'people_week': len({str(a.get('user') or '').lower() for a in week}),
                     'asks_week': len(week),
                     'people_total': len({str(a.get('user') or '').lower() for a in asks}),
                     'first_at': str(e.get('first_at') or ''),
                     'sample': int(size['sample']) if size and size.get('sample') else None,
                     'people_size': int(size['people']) if size and size.get('people') else None})
    rows.sort(key=lambda r: (-r['people_week'], -r['asks_week'], -r['people_total'], r['name'].lower()))
    return rows[:limit]


def _day(d):
    return f"{d:%b} {d.day}"


def _plural(n, one, many):
    return f"{n:,} {one if n == 1 else many}"


def build_ask(name) -> str:
    """The words that ask Prometheus for the build (the chip's words too)."""
    return f"Build a full profile of {name}"


def weekly_email(rows, *, now=None, days=WEEK_DAYS):
    """(subject line, plain text body) for the weekly list. Plain words,
    no em dashes, nothing about how anything was produced."""
    lo, hi = week_bounds(now, days)
    span = f"{_day(lo)} to {_day(hi)}"
    subject = f"Audiences people asked about that we don't have yet ({span})"
    lines = ["Hi Jenna,", "",
             f"These are the audiences people asked Prometheus about from {span} that we don't have a full profile for yet. "
             "The ones asked about most are at the top.", ""]
    for i, r in enumerate(rows, 1):
        lines.append(f"{i}. {r['name']}")
        asked = _plural(r['people_week'], 'person', 'people') + ' asked'
        if r['asks_week'] > r['people_week']:
            asked += f", {_plural(r['asks_week'], 'question', 'questions')} in all"
        lines.append(f"   {asked} this week.")
        if r['people_total'] > r['people_week']:
            first = _parse(r.get('first_at'))
            since = f" since {_day(first)}" if first else ''
            lines.append(f"   {_plural(r['people_total'], 'person has', 'people have')} asked{since}.")
        if r.get('people_size'):
            lines.append(f"   Audience size: {r['people_size']:,} people in the US.")
        else:
            lines.append("   Audience size: not sized yet. The brief will size it before the build.")
        lines.append(f"   To build it, send Prometheus this: {build_ask(r['name'])}")
        lines.append("")
    lines.append("Nothing gets built until you approve it. When you approve, the build uses the audience size shown here.")
    return subject, '\n'.join(lines)


def _ses():
    if SES_FOR_TESTS is not None:
        return SES_FOR_TESTS
    if _hermetic():
        return None
    import boto3
    return boto3.client('ses', region_name=SES_REGION)


def send_weekly(*, now=None, dry_run=False, force=False, s3=None, ses=None):
    """The Monday list. Sends to Jenna only, once per week, and nothing on
    an empty week. Returns {'week', 'rows', 'sent', 'reason'}."""
    s3 = s3 or _s3()
    week = week_tag(now)
    out = {'week': week, 'rows': 0, 'sent': False, 'reason': ''}
    if s3 is None:
        out['reason'] = 'no store'
        return out
    stamps = _load_json(s3, WEEKLY_KEY) or {}
    if not force and week in ((stamps.get('weeks') or {}) if isinstance(stamps, dict) else {}):
        out['reason'] = 'already sent this week'
        return out
    rows = weekly_rows(_load_json(s3, INDEX_KEY) or {}, now=now, s3=s3)
    out['rows'] = len(rows)
    subject, body = weekly_email(rows, now=now)
    out['subject'], out['body'] = subject, body
    if not rows:
        out['reason'] = 'empty week'
    elif dry_run:
        out['reason'] = 'dry run'
        return out
    else:
        client = ses or _ses()
        if client is None:
            out['reason'] = 'no mail client'
            return out
        client.send_email(Source=WEEKLY_FROM, Destination={'ToAddresses': list(WEEKLY_TO)},
                          Message={'Subject': {'Data': subject}, 'Body': {'Text': {'Data': body}}})
        out['sent'] = True
        out['reason'] = 'sent'
    if dry_run:
        return out
    t = _iso(_now(now))

    def mutate(doc):
        doc = doc if isinstance(doc, dict) else {}
        weeks = doc.setdefault('weeks', {})
        weeks[week] = {'at': t, 'rows': len(rows), 'sent': out['sent'],
                       'subjects': [r['name'] for r in rows]}
        if len(weeks) > 104:
            for k in sorted(weeks)[:len(weeks) - 104]:
                weeks.pop(k, None)
        return doc

    _update(s3, WEEKLY_KEY, mutate)
    return out


