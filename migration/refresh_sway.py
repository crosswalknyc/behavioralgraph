# ---------------------------------------------------------------- windows
def _d(s):
    try:
        return _dt.date.fromisoformat(str(s)[:10])
    except Exception:
        return None


def parse_window(value):
    """'START TO END', a SAMPLE SIZE label carrying one, or a {'start',
    'end'} dict -> {'start', 'end'} or None."""
    if isinstance(value, dict):
        s, e = str(value.get('start') or '')[:10], str(value.get('end') or '')[:10]
        return {'start': s, 'end': e} if _d(s) and _d(e) and _d(s) <= _d(e) else None
    m = _WINDOW_RX.search(str(value or ''))
    if not m or not (_d(m.group(1)) and _d(m.group(2))) or _d(m.group(1)) > _d(m.group(2)):
        return None
    return {'start': m.group(1), 'end': m.group(2)}


def window_days(w) -> int:
    a, b = _d((w or {}).get('start')), _d((w or {}).get('end'))
    if not (a and b) or b < a:
        return 0
    return (b - a).days + 1


def overlap_days(a, b) -> int:
    a0, a1 = _d((a or {}).get('start')), _d((a or {}).get('end'))
    b0, b1 = _d((b or {}).get('start')), _d((b or {}).get('end'))
    if not (a0 and a1 and b0 and b1):
        return 0
    lo, hi = max(a0, b0), min(a1, b1)
    return (hi - lo).days + 1 if hi >= lo else 0


def label(w) -> str:
    w = parse_window(w)
    return f"{w['start']} to {w['end']}" if w else ''


def changed_parts(old_w, new_w) -> list:
    """The parts of the two windows that differ: [{start, end, change}],
    change 'added' (in the new window only) or 'removed' (in the old
    window only)."""
    a0, a1 = _d((old_w or {}).get('start')), _d((old_w or {}).get('end'))
    b0, b1 = _d((new_w or {}).get('start')), _d((new_w or {}).get('end'))
    if not (a0 and a1 and b0 and b1):
        return []
    one = _dt.timedelta(days=1)
    out = []
    if b1 < a0 or a1 < b0:   # no shared day: each window is all changed
        return [{'start': b0.isoformat(), 'end': b1.isoformat(), 'change': 'added'},
                {'start': a0.isoformat(), 'end': a1.isoformat(), 'change': 'removed'}]
    if b0 < a0:
        out.append({'start': b0.isoformat(), 'end': (a0 - one).isoformat(), 'change': 'added'})
    if b0 > a0:
        out.append({'start': a0.isoformat(), 'end': (b0 - one).isoformat(), 'change': 'removed'})
    if b1 > a1:
        out.append({'start': (a1 + one).isoformat(), 'end': b1.isoformat(), 'change': 'added'})
    if b1 < a1:
        out.append({'start': (b1 + one).isoformat(), 'end': a1.isoformat(), 'change': 'removed'})
    return out


def _change_of(d, parts):
    for p in parts or []:
        p0, p1 = _d(p.get('start')), _d(p.get('end'))
        if p0 and p1 and p0 <= d <= p1:
            return p.get('change')
    return None


# ------------------------------------------------------------ the parent
def window_from_frame(df):
    """The window on a profile frame's SAMPLE SIZE row, or None."""
    try:
        cols = df['Column'].astype(str).str.strip().str.upper()
        for v in df.loc[cols == 'SAMPLE SIZE', 'Value'].tolist():
            w = parse_window(v)
            if w:
                return w
    except Exception:
        pass
    return None


def sample_from_frame(df):
    """The panel count on a profile frame's BRAND INPUT / SAMPLE SIZE row."""
    try:
        raw = next((c for c in ('Original Raw Numbers', 'Raw (Row)') if c in df.columns), None)
        if raw is None:
            return 0
        cols = df['Column'].astype(str).str.strip().str.upper()
        for v in df.loc[cols.isin(['BRAND INPUT', 'SAMPLE SIZE']), raw].tolist():
            try:
                n = int(round(float(str(v).replace(',', '').replace('%', '').strip())))
            except Exception:
                continue
            if n > 0:
                return n
    except Exception:
        pass
    return 0


