# ------------------------------------------------------------- the rows
def composition_level(p, g, r):
    """The level a row moves toward when the audience changes size by r:
    people added (r > 1) read like the general population (g) on the row,
    people lost (r < 1) were the casual ones. Between 0.01 and 99.4."""
    try:
        p, r = float(p), float(r)
        if g is None or not math.isfinite(p) or not math.isfinite(r) or r <= 0 or abs(r - 1.0) < 1e-9:
            return p
        g = float(g)
        if not math.isfinite(g):
            return p
        if r > 1.0:
            e = p / r + g * (1.0 - 1.0 / r)
        else:
            e = (p - (1.0 - r) * g) / r
            e = min(e, p / r)
            e = max(e, p * 0.25)
        return max(0.01, min(99.4, e))
    except Exception:
        return p


def _norm(s):
    return re.sub(r'[^a-z0-9]+', '', str(s or '').lower())


def affected_direction(value, sway):
    """'up' / 'down' when the row is one the events tie to, else None."""
    n = _norm(value)
    if not n or not isinstance(sway, dict):
        return None
    for a in sway.get('affected') or []:
        if _norm(a.get('value')) == n:
            return a.get('direction')
    return None


