def _subject_key(subject) -> str:
    f = re.sub(r'[^a-z0-9]+', '_', str(subject or '').lower()).strip('_')
    return f[:80] or 'unknown'


def record_key(subject) -> str:
    return f"{RECORD_PREFIX}{_subject_key(subject)}.json"


def _load(key, s3=None):
    if _STORE is not None:
        return _STORE.load(key)
    if _hermetic() and s3 is None:
        return None
    try:
        import boto3
        body = (s3 or boto3.client('s3')).get_object(Bucket=BUCKET, Key=key)['Body'].read()
        return json.loads(body)
    except Exception:
        return None


def _save(key, doc, s3=None):
    if _STORE is not None:
        _STORE.save(key, doc)
        return True
    if _hermetic() and s3 is None:
        return False
    try:
        import boto3
        (s3 or boto3.client('s3')).put_object(Bucket=BUCKET, Key=key, ContentType='application/json',
                                              Body=json.dumps(doc, indent=1, default=str).encode('utf-8'))
        return True
    except Exception:
        return False


def write_record(subject, v, *, run_id='', parent_key='', delivered=None, s3=None, log=print) -> bool:
    """Append the verdict to the subject's internal record (staff only).
    Records a researched verdict whether or not it applied, so the
    knowledge layer can read the dated events. Never raises."""
    try:
        if not isinstance(v, dict) or not v.get('researched'):
            return False
        key = record_key(subject)
        doc = _load(key, s3) or {'subject': str(subject or ''), 'records': []}
        rec = {'at': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()), 'run_id': run_id,
               'parent_key': parent_key, 'applies': bool(v.get('applies')), 'direction': v.get('direction'),
               'basis': v.get('basis'), 'parent_sample': v.get('parent_sample'),
               'delivered_sample': int(delivered or v.get('sample') or 0),
               'ratio': v.get('ratio'), 'ratio_lo': v.get('ratio_lo'), 'ratio_hi': v.get('ratio_hi'),
               'parent_window': v.get('parent_window'), 'new_window': v.get('new_window'),
               'events': v.get('events') or [], 'anchors': v.get('anchors') or [],
               'affected': v.get('affected') or [], 'house': v.get('house'),
               'reason': v.get('reason') or '', 'why_not': v.get('why_not') or ''}
        doc['records'] = ([r for r in (doc.get('records') or []) if isinstance(r, dict)] + [rec])[-RECORD_CAP:]
        ok = _save(key, doc, s3)
        clear_cache()
        return ok
    except Exception as e:
        try:
            log(f"refresh sway: record skipped ({type(e).__name__})")
        except Exception:
            pass
        return False


def recorded(subject, s3=None) -> list:
    """The subject's records, newest last (cached). Never raises."""
    key = record_key(subject)
    now = time.time()
    with _lock:
        hit = _cache.get(key)
    if hit and now - hit[0] < CACHE_TTL_S:
        return list(hit[1])
    doc = _load(key, s3) or {}
    recs = [r for r in (doc.get('records') or []) if isinstance(r, dict)]
    with _lock:
        _cache[key] = (now, recs)
    return list(recs)


def recorded_events(subject, s3=None) -> list:
    """Every dated event a refresh read recorded for the subject, as
    [{date, kind, name}] (the shape prometheus.consistency reads), one per
    date and kind. Never raises."""
    try:
        out, seen = [], set()
        for r in recorded(subject, s3):
            for e in r.get('events') or []:
                if not isinstance(e, dict) or not _d(e.get('date')):
                    continue
                k = (str(e.get('date'))[:10], str(e.get('kind') or ''))
                if k in seen:
                    continue
                seen.add(k)
                out.append({'date': k[0], 'kind': k[1], 'name': str(e.get('name') or k[1])})
        return sorted(out, key=lambda x: x['date'])
    except Exception:
        return []


