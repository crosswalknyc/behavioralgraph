class MemoryStore:
    """An in-memory record store (tests, hermetic runs)."""

    def __init__(self):
        self.docs = {}

    def load(self, key):
        d = self.docs.get(key)
        return json.loads(json.dumps(d)) if d is not None else None

    def save(self, key, doc):
        self.docs[key] = json.loads(json.dumps(doc, default=str))


