"""Research-justified sway for time-shifted refreshes (2026-11-24).

Jenna, verbatim: "alexia is doing an updated profile on stephen colbert
and we need to take into account that he had a much better year for
2026 so it would most definitely look different than the 2025 so
monitor it to make sure accurately does 2026 and it's not too governed
by the 2025 profile and that we have something built in to realize it
can sway if there is a good reason during that time period to do so."

A time-shifted refresh is anchored to the profile it refreshes (the
parent). Before this module the parent governed the new window in four
places, with no way to tell a real change from a re-guess:

* the size: the refresh guard in migration/synth_queue_worker.py held
  the sample inside +/-15% of the parent, and its window research
  labelled the parent's window with the file's BUILD date (Colbert's
  calendar-2025 profile was compared as "June 2026" against "November
  2026", show on air against show over, and read as a 40% decline);
* the rows: migration/sibling_level_hold.py held every shared brand
  row to a band around the parent (mass reach +/-12%, general +/-35%)
  and every demographic bucket to +/-4 points, and handed the parent's
  levels to the reasoner as "published levels";
* the Avid cohort, which read the Total Universe's parent levels too;
* the benchmark's prior-window check, which lifts a build below 0.6x
  of the prior Total Universe back up unless a reason is stated.

What this module does
---------------------
One research call (web search) per refresh compares the two windows as
windows: the parent's own dates (its SAMPLE SIZE row) against the new
window. It asks for

1. dated events that plausibly moved the subject's US audience, inside
   the part of the new window the parent does not cover ("added") or
   inside the part of the parent window the new one drops ("removed"):
   a final season or finale, a cancellation, an award, a release or
   premiere, a tour, a new show, a launch or campaign, a viral moment, a
   run of major press, a notable appearance, a controversy, a hiatus or
   the end of a show (``KINDS``);
2. countable anchors for the audience in each window from approved
   sources only (platform-reported counts, measured viewership as
   published, network and company statements, filings and earnings,
   Pew, YouGov, Statista, eMarketer, app analytics; never store visits,
   household device counts, cable reach or total brand reach);
3. a range for the ratio of US people engaged online in the new window
   to those in the parent's window.

The sway applies only when the evidence has a direction (the whole
researched range above or below 1, or the house's own read of the new
window, below) and at least one validated event implies the same
direction: an event added in that direction, or one in the opposite
direction that the new window drops. Then

* the size leaves the parent band and lands at the LOW end of the
  researched range (the bottom third, subject-salted,
  calibrate-low-anchor-to-actuals.mdc). When the subject's Gen Pop row
  measures most of the new window (the house's own read of it), that
  read is the anchor: the sample lands at the low end of it
  (``HOUSE_BAND``), never above it;
* the rows: the sibling hold widens each shared row's band toward the
  level the changed audience implies (people added read like the
  general population on everyday brands, people lost were the casual
  ones), extends the band of the rows the events tie to, widens the
  demographic hold the same way and stops reading a real composition
  shift as "a different basis"; the reasoner is told the window carries
  the events;
* the benchmark's prior-window check and its Gen Pop check (when the
  Gen Pop row measures mostly another period) do not undo a researched
  move; the saved-size path never re-sizes a swayed refresh; the
  knowledge layer's near-twin holds read the recorded events as their
  research override (prometheus/knowledge.py).

Without a validated event and a direction, nothing changes: the
existing band holds. Research failure is the same as no evidence.

The events, the anchors and the lift are recorded internally only: the
run status, the worker log, the internal ops line and
``system/refresh_sway/<subject>.json``. Nothing a reader sees names
them (no-modeled-or-source-language.mdc). Kill switch REFRESH_SWAY=0
(env only); REGRESSION_TEST_MODE=1 makes no network or S3 call unless a
call or store is injected.

Lives in both repos (migration/ in the parent is the source,
bg-webapp/migration/ is generated by scripts/sync_module_twins.py).
Never raises. Regression: scripts/test_refresh_sway.py.
"""
